// v0.47: a payee's own approval line, offline.
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { parseUnits } from "viem";
process.env.REINPAY_HOME = mkdtempSync(join(tmpdir(), "reinpay-payeeline-"));
const { decide } = await import("../src/rules.js"), { explain } = await import("../src/explain.js"), { headroom } = await import("../src/headroom.js");
const C = await import("../src/config.js"), P = await import("../src/pay.js");
let pass = 0, fail = 0;
const check = (label, cond, info = "") => { cond ? pass++ : fail++; console.log(`${cond ? "PASS" : "FAIL"} ${label}${info ? ` (${info})` : ""}`); };
const NOW = Date.parse("2026-11-20T12:00:00"), eth = (x) => parseUnits(String(x), 18);
const G = "0x00000000000000000000000000000000DeaDBeef", W = "0x000000000000000000000000000000000000dEaD";
const rules = { daily: { ETH: 0.005 }, maxPerPayment: { ETH: 0.002 }, approveAbove: { ETH: 0.001 } };
const gpu = { name: "GPU credits", address: G, approveAbove: { ETH: "0.0003" } }, weather = { name: "Weather API", address: W };
const D = (payee, amt) => decide({ rules, receipts: [], request: { payee, token: "ETH", amountRaw: eth(amt) }, now: NOW });
const d = D(gpu, "0.0005");
check("above the payee's own line: waits for you, named for that payee", d.status === "needs_approval" && d.rule === "payee approval line" && /approval line you set for GPU credits \(0\.0003 ETH\)/.test(d.reason), d.reason);
check("under it: goes through", D(gpu, "0.0002").status === "allowed");
check("another payee keeps the general line", D(weather, "0.0005").status === "allowed" && D(weather, "0.0015").rule === "approval line");
check("a hard limit still comes first: above the max is blocked, not waiting", D(gpu, "0.003").rule === "max per payment");
check("check --explain marks it", explain({ rules, receipts: [], request: { payee: gpu, token: "ETH", amountRaw: eth("0.0005") }, now: NOW }).steps.find((s) => s.decided)?.rule === "payee approval line");
const hr = headroom({ rules, receipts: [], payees: [gpu], now: NOW }).find((r) => r.token === "ETH");
check("headroom: up to 0.0003 without you, up to 0.002 with your yes", hr.free === eth("0.0003") && hr.withYou === eth("0.002") && hr.freeStop === "payee approval line");
C.saveConfig({ ...C.DEFAULT_CONFIG, payees: [{ name: "GPU credits", address: G, isContract: false, addedAt: "2026-11-20T00:00:00Z" }] });
P.setPayeeLimit("GPU credits", "ask-above", "ETH", "0.0003");
check("payee limit ask-above sets it", C.loadConfig().payees[0].approveAbove.ETH === "0.0003");
P.setPayeeLimit("GPU credits", "ask-above", "ETH", "off");
check("and off removes it", C.loadConfig().payees[0].approveAbove === undefined);
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
